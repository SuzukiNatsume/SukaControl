    public static string Error(Exception ex)
    {
        Store.Log(ex.ToString());
        if (ex is UnauthorizedAccessException || ex.Message.Contains("Access denied", StringComparison.OrdinalIgnoreCase) || ex.Message.Contains("管理员")) return T("adminRequired");
        if (ex.Message.Contains("需要接通电源")) return T("acRequired");
        if (ex.Message.Contains("Gamma") || ex.Message.Contains("色温") || ex.Message.Contains("护眼")) return T("eyeError");
        if (ex.Message.Contains("色彩") || ex.Message.Contains("ICC")) return T("profileError");
        return T("hardwareError");
    }
